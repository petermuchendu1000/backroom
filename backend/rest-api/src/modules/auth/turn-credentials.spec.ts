import { ConfigService } from '@nestjs/config';
import { JwtService } from '@nestjs/jwt';
import { Test } from '@nestjs/testing';
import { getRepositoryToken } from '@nestjs/typeorm';
import { User } from '../../database/entities/user.entity';
import { SubscriptionsService } from '../subscriptions/subscriptions.service';
import { AuthService } from './auth.service';

/**
 * TURN credentials, pinned to the same vector as the Go implementation.
 *
 * Two services mint credentials coturn must accept: this one, for
 * GET /auth/turn-credentials, and the signalling hub, which puts them on every
 * matchMade. coturn recomputes the HMAC itself, so all three have to agree exactly —
 * and a disagreement is invisible until a call needs a relay and silently fails to
 * connect, which is the hardest kind of bug to attribute.
 *
 * The constants below are identical to the ones in
 * backend/ws-signaling/internal/turn/credentials_test.go, and neither came from
 * either implementation: both were generated by a Python HMAC written from coturn's
 * documented scheme. Matching the same third party is what makes them match each
 * other, and it is checked on both sides rather than asserted once.
 */
const SECRET = 'ongero-turn-test-secret';
const USER_ID = '11111111-2222-3333-4444-555555555555';
const EXPECTED_USERNAME = '1800000000:11111111-2222-3333-4444-555555555555';
const EXPECTED_CREDENTIAL = 'MUDBi9THQCXWEwsXefDglfM6Mps=';

/** The instant that makes a 3600s TTL land on the vector's expiry. */
const NOW_MS = (1800000000 - 3600) * 1000;

describe('AuthService.generateTurnCredentials', () => {
  let service: AuthService;
  let config: Record<string, unknown>;

  beforeEach(async () => {
    config = {
      'turn.secret': SECRET,
      'turn.ttl': 3600,
      'turn.url': 'turn:turn.ongero.com:3478',
      'turn.stunUrl': 'stun:stun.l.google.com:19302',
    };

    const moduleRef = await Test.createTestingModule({
      providers: [
        AuthService,
        { provide: getRepositoryToken(User), useValue: {} },
        { provide: JwtService, useValue: { sign: jest.fn() } },
        { provide: ConfigService, useValue: { get: (k: string) => config[k] } },
        { provide: SubscriptionsService, useValue: { currentTier: jest.fn() } },
      ],
    }).compile();

    service = moduleRef.get(AuthService);
    jest.spyOn(Date, 'now').mockReturnValue(NOW_MS);
  });

  afterEach(() => jest.restoreAllMocks());

  it('matches the vector the Go signalling service is pinned to', () => {
    const credentials = service.generateTurnCredentials(USER_ID);

    expect(credentials.username).toBe(EXPECTED_USERNAME);
    expect(credentials.credential).toBe(EXPECTED_CREDENTIAL);
  });

  it('puts the expiry first, which is the part coturn enforces', () => {
    const credentials = service.generateTurnCredentials(USER_ID);

    const [expiry, rest] = credentials.username.split(':');
    expect(Number(expiry)).toBe(Math.floor(NOW_MS / 1000) + 3600);
    expect(rest).toBe(USER_ID);
  });

  it('offers both STUN and TURN, so a direct connection is still tried first', () => {
    const credentials = service.generateTurnCredentials(USER_ID);

    expect(credentials.urls).toContain('stun:stun.l.google.com:19302');
    expect(credentials.urls).toContain('turn:turn.ongero.com:3478');
    expect(credentials.ttl).toBe(3600);
  });

  it('produces a different credential under a different secret', () => {
    const withOurSecret = service.generateTurnCredentials(USER_ID).credential;
    config['turn.secret'] = 'a-different-secret';

    expect(service.generateTurnCredentials(USER_ID).credential).not.toBe(withOurSecret);
  });

  it('produces a credential coturn can decode: 20 base64 bytes', () => {
    // base64(HMAC-SHA1(...)). A hex digest is 40 characters and would simply be the
    // wrong password, with no error that says so.
    const { credential } = service.generateTurnCredentials(USER_ID);

    expect(credential).toHaveLength(28);
    expect(Buffer.from(credential, 'base64')).toHaveLength(20);
  });
});
